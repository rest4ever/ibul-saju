const KEYS = Object.keys(GLOSS).sort((a, b) => b.length - a.length);
// 한 글자짜리처럼 오해되기 쉬운 말은 앞뒤가 한글이 아닐 때만
const STRICT = new Set(['해', '충', '사주', '음양']);
const RE = new RegExp(KEYS.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const RE1 = new RegExp(RE.source);
const SKIP = new Set(['BUTTON', 'SCRIPT', 'STYLE', 'H2', 'SUMMARY', 'SELECT', 'OPTION', 'TEXTAREA', 'INPUT', 'LABEL']);

export function markTerms(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(n) {
      for (let p = n.parentElement; p && p !== root; p = p.parentElement) {
        if (SKIP.has(p.tagName) || p.classList.contains('term') || p.classList.contains('cell') || p.classList.contains('no-term')) return NodeFilter.FILTER_REJECT;
      }
      return RE1.test(n.nodeValue) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((n) => {
    const s = n.nodeValue;
    const frag = document.createDocumentFragment();
    let last = 0;
    RE.lastIndex = 0;
    let m;
    const used = new Set();
    while ((m = RE.exec(s))) {
      const k = m[0];
      const before = s[m.index - 1] || '', after = s[m.index + k.length] || '';
      if (STRICT.has(k) && (/[가-힣]/.test(before) || /[가-힣]/.test(after))) continue;
      if (used.has(k)) continue;   // 한 문단에 같은 말은 한 번만 표시
      used.add(k);
      frag.appendChild(document.createTextNode(s.slice(last, m.index)));
      const b = document.createElement('button');
      b.type = 'button'; b.className = 'term'; b.dataset.t = k; b.textContent = k;
      frag.appendChild(b);
      last = m.index + k.length;
    }
    if (!last) return;
    frag.appendChild(document.createTextNode(s.slice(last)));
    n.parentNode.replaceChild(frag, n);
  });
}
export function showTerm(k) {
  const g = document.getElementById('gloss');
  document.getElementById('gloss-t').textContent = k;
  document.getElementById('gloss-x').textContent = GLOSS[k] || '';
  g.hidden = false;
}
export function initGloss() {
  document.addEventListener('click', (e) => {
    const t = e.target.closest('.term');
    if (t) { e.preventDefault(); showTerm(t.dataset.t); return; }
    if (e.target.closest('#gloss-close') || (e.target.id === 'gloss')) document.getElementById('gloss').hidden = true;
  });
}
